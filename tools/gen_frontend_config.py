"""Compile model/frontend.json into the firmware header (architecture §7.3 parity rule).

The header carries every parameter plus the SHA-256 of the JSON bytes, which the firmware
prints at boot and the model metadata will record. Run by tools/idf.ps1 before each build.
"""
import hashlib
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "model" / "frontend.json"
DST = ROOT / "firmware" / "components" / "microfrontend" / "include" / "ps_frontend_config.h"

raw = SRC.read_bytes()
c = json.loads(raw)
sha = hashlib.sha256(raw).hexdigest()

lines = [
    "/* GENERATED by tools/gen_frontend_config.py from model/frontend.json — do not edit. */",
    "#pragma once",
    f'#define PS_FE_JSON_SHA256 "{sha}"',
    f"#define PS_FE_SAMPLE_RATE_HZ {c['sample_rate_hz']}",
    f"#define PS_FE_WINDOW_MS {c['window_ms']}",
    f"#define PS_FE_HOP_MS {c['hop_ms']}",
    f"#define PS_FE_MEL_BANDS {c['mel_bands']}",
    f"#define PS_FE_MEL_LOW_HZ {float(c['mel_low_hz'])!r}f",
    f"#define PS_FE_MEL_HIGH_HZ {float(c['mel_high_hz'])!r}f",
    f"#define PS_FE_FB_OUTPUT_SCALE_SHIFT {c['filterbank_output_scale_shift']}",
    f"#define PS_FE_NR_SMOOTHING_BITS {c['noise_reduction']['smoothing_bits']}",
    f"#define PS_FE_NR_EVEN_SMOOTHING {float(c['noise_reduction']['even_smoothing'])!r}f",
    f"#define PS_FE_NR_ODD_SMOOTHING {float(c['noise_reduction']['odd_smoothing'])!r}f",
    f"#define PS_FE_NR_MIN_SIGNAL_REMAINING {float(c['noise_reduction']['min_signal_remaining'])!r}f",
    f"#define PS_FE_PCAN_ENABLE {c['pcan']['enable']}",
    f"#define PS_FE_PCAN_STRENGTH {float(c['pcan']['strength'])!r}f",
    f"#define PS_FE_PCAN_OFFSET {float(c['pcan']['offset'])!r}f",
    f"#define PS_FE_PCAN_GAIN_BITS {c['pcan']['gain_bits']}",
    f"#define PS_FE_LOG_ENABLE {c['log_scale']['enable']}",
    f"#define PS_FE_LOG_SCALE_SHIFT {c['log_scale']['scale_shift']}",
    "",
]
text = "\n".join(lines)
if not DST.exists() or DST.read_text(encoding="utf-8") != text:  # keep mtime stable when unchanged
    DST.write_text(text, encoding="utf-8")
print(f"frontend.json sha256={sha[:16]}… -> {DST.relative_to(ROOT)}")
