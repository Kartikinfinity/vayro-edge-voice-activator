"""Embed a trained int8 model into the firmware (SS-4 kws_engine).

Writes firmware/components/kws_engine/model_data.c with the .tflite bytes (const -> flash,
architecture T-04), its SHA-256, the front-end SHA-256 it was trained with (the firmware refuses a
mismatch, §7.3 point 4) and the int8 input LUT computed EXACTLY as model/eval/eval_stream.py does,
so device and host feed the model identical bytes.

Usage: python tools/gen_model_source.py model/artifacts/v1
"""
import hashlib
import json
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
art = pathlib.Path(sys.argv[1])
if not art.is_absolute():
    art = ROOT / art
tfl = (art / "model_int8.tflite").read_bytes()
m = json.loads((art / "metrics.json").read_text(encoding="utf-8"))
isc, izp = m["input_quant"]
lut = np.clip(np.round(np.arange(-128, 128) / 128.0 / isc + izp), -128, 127).astype(np.int8)
sha = hashlib.sha256(tfl).hexdigest()
assert sha == m["tflite_sha256"], "metrics.json does not describe this .tflite"

body = ",".join(str(b) for b in tfl)
src = f"""/* GENERATED by tools/gen_model_source.py from model/artifacts/{art.name} — do not edit. */
#include "model_data.h"

const char g_kws_model_run[] = "{art.name}";
const char g_kws_model_sha256[] = "{sha}";
const char g_kws_model_fe_sha256[] = "{m['data_meta']['frontend_sha256']}";
const unsigned int g_kws_model_len = {len(tfl)};
const int8_t g_kws_input_lut[256] = {{{",".join(str(int(v)) for v in lut)}}};
__attribute__((aligned(16))) const unsigned char g_kws_model[] = {{{body}}};
"""
dst = ROOT / "firmware" / "components" / "kws_engine" / "model_data.c"
dst.write_text(src, encoding="utf-8")

# The operating point travels with the model (model/artifacts/selection_*_outcome.json -> firmware/sdkconfig.model).
sel_files = sorted((ROOT / "model" / "artifacts").glob("selection_*_outcome.json"))
match = next(((f, json.loads(f.read_text(encoding="utf-8"))["selected"]) for f in reversed(sel_files)
              if json.loads(f.read_text(encoding="utf-8")).get("selected", {}).get("model") == art.name), None)
if match:
    sel_file, sel = match
    (ROOT / "firmware" / "sdkconfig.model").write_text(
        f"# GENERATED by tools/gen_model_source.py: operating point of model {art.name} ({sel_file.name})\n"
        f"CONFIG_PS_KWS_THRESHOLD_PCT={round(sel['threshold'] * 100)}\n"
        f"CONFIG_PS_KWS_AVG_N={sel['N']}\n"
        f"CONFIG_PS_KWS_STRIDE_FRAMES={sel['stride_frames']}\n"
        f"CONFIG_PS_KWS_REFRACTORY_MS={round(sel['refractory_s'] * 1000)}\n", encoding="utf-8")
    print(f"operating point: thr {sel['threshold']} N {sel['N']} -> firmware/sdkconfig.model")
print(f"model {art.name}: {len(tfl)} B sha256={sha[:16]}... fe={m['data_meta']['frontend_sha256'][:16]}... -> {dst.relative_to(ROOT)}")
