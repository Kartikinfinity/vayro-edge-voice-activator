"""Export the host twin's canonical init tables (filterbank weights/unweights, PCAN gain LUT) to
firmware/components/microfrontend/ps_frontend_tables.c. The device copies them over its own
libm-computed tables after init, making device features bit-identical to the training features.
Re-run whenever model/frontend.json changes (the file records the JSON SHA-256; the device refuses a
mismatch). Run in WSL (loads libpsfe.so)."""
import ctypes
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from model.frontend.psfe import Frontend  # noqa: E402

fe = Frontend()
lib = fe._lib
nw, nl = ctypes.c_size_t(), ctypes.c_size_t()
lib.ps_fe_table_sizes(ctypes.byref(nw), ctypes.byref(nl))
W, U, L = (ctypes.c_int16 * nw.value)(), (ctypes.c_int16 * nw.value)(), (ctypes.c_int16 * nl.value)()
lib.ps_fe_get_tables(W, U, L)
arr = lambda a: ",".join(str(v) for v in a)  # noqa: E731
src = f"""/* GENERATED by model/frontend/export_tables.py from the host twin — do not edit.
 * Canonical front-end tables (M2 parity fix, DEC-16). frontend.json SHA-256 below must match the firmware's. */
#include <stddef.h>
#include <stdint.h>

const char ps_fe_tables_fe_sha256[] = "{fe.sha256}";
const size_t ps_fe_tables_n_weights = {nw.value};
const size_t ps_fe_tables_n_lut = {nl.value};
const int16_t ps_fe_tables_weights[] = {{{arr(W)}}};
const int16_t ps_fe_tables_unweights[] = {{{arr(U)}}};
const int16_t ps_fe_tables_lut[] = {{{arr(L)}}};
"""
dst = ROOT / "firmware" / "components" / "microfrontend" / "ps_frontend_tables.c"
dst.write_text(src, encoding="utf-8")
print(f"exported weights[{nw.value}] unweights[{nw.value}] lut[{nl.value}] fe={fe.sha256[:16]} -> {dst.relative_to(ROOT)}")
